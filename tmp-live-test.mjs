import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
const LIVE = 'https://dealwirth.github.io/hitster-web/';
const b = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox'] });
const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 } });
const p = await ctx.newPage();
const errors = [];
p.on('pageerror', e => errors.push('pageerror: ' + e.message));
p.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
await p.goto(LIVE + '?start=1&live=' + Date.now(), { waitUntil: 'networkidle' });
await p.waitForFunction(() => window.HITSTER?.state?.ready, { timeout: 45000 });
console.log('loaded', await p.evaluate(() => ({ songs: HITSTER.state.songs.length, static: HITSTER.STATIC, start: getComputedStyle(document.querySelector('#startScreen')).display, cards: document.querySelectorAll('[data-start]').length })));
assert.equal(await p.locator('#startScreen').isVisible(), true);
assert.equal(await p.locator('[data-start]').count(), 6);
await p.locator('[data-start="classic"]').click();
await p.waitForTimeout(600);
assert.equal(await p.locator('#gameLayout').isVisible(), true);
const front = await p.locator('#cardFront').innerText();
console.log('front chars', front.length);
const yearNow = await p.evaluate(() => HITSTER.state.current.year);
assert.ok(!front.includes(String(yearNow)), 'front leaks year: ' + front);
await p.locator('#cardPlay').click();
await p.waitForFunction(() => document.querySelector('#card')?.classList.contains('is-playing'), { timeout: 20000 });
await p.waitForTimeout(1200);
console.log('audio', await p.evaluate(() => { const a=document.querySelector('#audio'); return { paused:a.paused, time:a.currentTime, src:a.currentSrc.slice(0,80) }; }));
assert.equal(await p.evaluate(() => document.querySelector('#audio').paused), false);
await p.locator('#flipBtn').click();
await p.waitForTimeout(900);
assert.equal(await p.locator('#card').getAttribute('data-flipped'), 'true');
console.log('back', await p.evaluate(() => ({ title: document.querySelector('#backTitle').textContent, cats: [...document.querySelectorAll('#backCats span')].map(e=>e.textContent), year: document.querySelector('#backYear')?.textContent })));
assert.ok((await p.locator('#backCats span').count()) >= 2);
await p.locator('#spotifyBtn').click();
await p.waitForTimeout(500);
assert.equal(await p.locator('#spotifyModal').isVisible(), true);
console.log('spotify', await p.evaluate(() => ({ frame: document.querySelector('#spotifyFrame iframe')?.src || '', open: document.querySelector('#spotifyOpen')?.href })));
await p.keyboard.press('Escape');
await p.waitForTimeout(250);
await p.locator('.mode-btn[data-mode="versions"]').click();
await p.waitForTimeout(300);
await p.locator('[data-version="party"]').click();
await p.waitForTimeout(500);
console.log('version', await p.evaluate(() => ({ mode: HITSTER.state.mode, version: HITSTER.state.version, url: location.search })));
await p.evaluate(() => { window.print = () => { window.__printed = true; }; window.HITSTER.openPrint(); });
await p.waitForTimeout(250);
await p.selectOption('#printCount', '9');
await p.locator('#printGo').click();
await p.waitForTimeout(1200);
console.log('print', await p.evaluate(() => ({ printed: window.__printed, cards: document.querySelectorAll('#printRoot .print-card').length, qrs: document.querySelectorAll('#printRoot .pc-qr img').length, cats: document.querySelectorAll('#printRoot .pc-cats span').length })));
assert.equal(await p.evaluate(() => window.__printed), true);
await p.waitForTimeout(200);
assert.deepEqual(errors, []);
console.log('errors', errors);
await b.close();
